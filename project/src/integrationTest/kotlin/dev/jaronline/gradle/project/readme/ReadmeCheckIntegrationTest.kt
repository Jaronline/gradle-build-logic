package dev.jaronline.gradle.project.readme

import org.gradle.api.GradleException
import org.gradle.api.Project
import org.gradle.testfixtures.ProjectBuilder
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.BeforeEach
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.assertDoesNotThrow
import org.junit.jupiter.api.assertThrows
import org.junit.jupiter.api.io.TempDir
import java.io.File

class ReadmeCheckIntegrationTest {
	@field:TempDir
	lateinit var projectDir: File
	lateinit var project: Project

	@BeforeEach
	fun setup() {
		project = ProjectBuilder.builder().withProjectDir(projectDir).build()
	}

	@Test
	fun `test checkReadme with root README AND root README equals generated README does not throw`() {
		val generatedReadmeFile =
			projectDir.resolve("generated-README.md").apply {
				writeText("This is some data")
			}
		val rootReadmeFile =
			projectDir.resolve("README.md").apply {
				writeText("This is some data")
			}

		val readmeCheck =
			project.tasks.register("readmeCheck", ReadmeCheck::class.java) {
				this.generatedReadme.set(generatedReadmeFile)
				this.rootReadme.set(rootReadmeFile)
			}

		assertDoesNotThrow {
			readmeCheck.get().checkReadme()
		}
	}

	@Test
	fun `test checkReadme with root README AND root README does not equal generated README throws GradleException`() {
		val generatedReadmeFile =
			projectDir.resolve("generated-README.md").apply {
				writeText("This is some data")
			}
		val rootReadmeFile =
			projectDir.resolve("README.md").apply {
				writeText("This is some other data")
			}

		val readmeCheck =
			project.tasks.register("readmeCheck", ReadmeCheck::class.java) {
				this.generatedReadme.set(generatedReadmeFile)
				this.rootReadme.set(rootReadmeFile)
			}

		val exception =
			assertThrows<GradleException> {
				readmeCheck.get().checkReadme()
			}
		assertEquals(
			"${rootReadmeFile.path} differs from the README generated by the template in ${generatedReadmeFile.path}. Update the template, then run the updateReadme task",
			exception.message,
		)
	}
}
