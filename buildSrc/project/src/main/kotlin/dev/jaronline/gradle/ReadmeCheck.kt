package dev.jaronline.gradle

import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.Optional
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

abstract class ReadmeCheck : DefaultTask() {
	@get:InputFile
	@get:PathSensitive(PathSensitivity.NONE)
	abstract val generatedReadme: RegularFileProperty

	@get:InputFile
	@get:Optional
	@get:PathSensitive(PathSensitivity.NONE)
	abstract val rootReadme: RegularFileProperty

	@TaskAction
	fun checkReadme() {
		val expected = generatedReadme.get().asFile
		val actual = rootReadme.orNull?.asFile

		if (actual == null || !actual.isFile) {
			throw GradleException("Could not find root README.md file." +
					"Generate the README.md file using the updateReadme task")
		}

		if (!expected.readBytes().contentEquals(actual.readBytes())) {
			val rootPath = actual.relativeTo(project.projectDir).path
			val generatedPath = expected.relativeTo(project.projectDir).path
			throw GradleException("$rootPath differs from the README generated by the template in $generatedPath. " +
				"Update the template, then run the updateReadme task")
		}
	}
}